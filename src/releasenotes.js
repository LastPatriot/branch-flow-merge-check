// Release notes. Pure functions: no Forge or network code, so they can be tested directly.
//
// Input is the merged PR's commits. Bitbucket's merge commits ("Merged in fix/x (pull request #12)")
// identify the PRs that were released; promotion merges between long-lived branches
// (dev, test, prod) are skipped. Other commits are listed under "Other commits".

import { isVersionLine } from './rules.js';

const MERGED_PR = /^Merged in (\S+) \(pull request #(\d+)\)/;
const LONG_LIVED = ['dev', 'test', 'prod'];

const firstLine = (message) => (message || '').split('\n')[0].trim();

function sectionFor(branch) {
  if (branch.startsWith('feature/')) return 'Features';
  if (branch.startsWith('fix/')) return 'Fixes';
  if (branch.startsWith('hotfix/')) return 'Hotfixes';
  return 'Other pull requests';
}

const SECTION_ORDER = ['Features', 'Fixes', 'Hotfixes', 'Other pull requests', 'Other commits'];

// commits: Bitbucket commit objects ({ hash, message, author: { raw, user: { display_name } } }).
export function collectChanges(commits) {
  const sections = Object.fromEntries(SECTION_ORDER.map((s) => [s, []]));
  const seenPrs = new Set();
  const seenLines = new Set();

  for (const commit of commits) {
    const line = firstLine(commit.message);
    if (!line) continue;

    const merged = line.match(MERGED_PR);
    if (merged) {
      const [, branch, pr] = merged;
      if (LONG_LIVED.includes(branch) || isVersionLine(branch) || seenPrs.has(pr)) continue;
      seenPrs.add(pr);
      sections[sectionFor(branch)].push(`${branch} (#${pr})`);
      continue;
    }

    // Other merge commits ("Merge branch ...", "Merge remote-tracking branch ...") carry no change of their own.
    if (/^Merge (branch|remote-tracking branch|pull request)\b/.test(line)) continue;
    if (seenLines.has(line)) continue;
    seenLines.add(line);
    const author = commit.author?.user?.display_name || (commit.author?.raw || '').replace(/\s*<.*>$/, '');
    const meta = [author, (commit.hash || '').slice(0, 7)].filter(Boolean).join(', ');
    sections['Other commits'].push(meta ? `${line} (${meta})` : line);
  }
  return sections;
}

// pr: { id, title, source, target, mergeCommit, mergedAt }. Returns Markdown for a PR comment.
export function buildReleaseNotes(pr, commits, { maxPerSection = 50 } = {}) {
  const sections = collectChanges(commits);
  const env = pr.target === 'prod' ? 'production' : pr.target === 'test' ? 'staging' : pr.target;
  const lines = [
    `## Release notes: ${pr.source} → ${pr.target} (${env})`,
    '',
    `Pull request #${pr.id}: ${pr.title}`,
  ];
  if (pr.mergeCommit) lines.push(`Merge commit: ${pr.mergeCommit.slice(0, 12)}`);
  if (pr.mergedAt) lines.push(`Merged: ${pr.mergedAt}`);

  let total = 0;
  for (const name of SECTION_ORDER) {
    const items = sections[name];
    if (items.length === 0) continue;
    total += items.length;
    lines.push('', `### ${name}`);
    for (const item of items.slice(0, maxPerSection)) lines.push(`- ${item}`);
    if (items.length > maxPerSection) lines.push(`- …and ${items.length - maxPerSection} more`);
  }
  if (total === 0) lines.push('', 'No changes found in this pull request’s commits.');
  if (commits.truncated) lines.push('', '_Commit list was truncated; older commits are not included._');

  lines.push('', '_Generated by the Git Branching Strategy app._');
  return lines.join('\n');
}

// Target branches that get release notes: comma-separated, default test and prod.
export function notesTargetAllowed(target, setting) {
  return (setting || 'test,prod')
    .split(',')
    .map((t) => t.trim())
    .filter(Boolean)
    .includes(target);
}
